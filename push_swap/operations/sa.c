#include "libft.h"

void	sa(int *A, int *size_a, t_ops *ops)
{
	int	tmp;
	int	a;

	a = *size_a;
	if (a > 1)
	{
		tmp = A[0];
		A[0] = A[1];
		A[1] = tmp;
		ops->sa++;
		ops->total++;
		ft_putstr_fd("sa\n", 1);
	}
}
