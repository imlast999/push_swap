#include "libft.h"

void	sb(int *B, int *size_b, t_ops *ops)
{
	int	tmp;
	int	b;

	b = *size_b;
	if (b > 1)
	{
		tmp = B[0];
		B[0] = B[1];
		B[1] = tmp;
		ops->sb++;
		ops->total++;
		ft_putstr_fd("sb\n", 1);
	}
}
