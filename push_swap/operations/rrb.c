#include "libft.h"

void	rrb(int *B, int *size_b, t_ops *ops)
{
	int	b;
	int	tmp;

	b = *size_b - 1;
	if (*size_b > 1)
	{
		tmp = B[b];
		while (b > 0)
		{
			B[b] = B[b - 1];
			b--;
		}
		B[0] = tmp;
		ops->rrb++;
		ops->total++;
		ft_putstr_fd("rrb\n", 1);
	}
}
