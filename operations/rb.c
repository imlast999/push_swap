#include "push_swap.h"

void	rb(int *B, int *size_b, t_ops *ops)
{
	int	b;
	int	i;
	int	tmp;

	b = *size_b;
	if (b > 1)
	{
		tmp = B[0];
		i = 0;
		while (b - 1 > i)
		{
			B[i] = B[i + 1];
			i++;
		}
		B[i] = tmp;
		ops->rb++;
		ops->total++;
		ft_putstr_fd("rb\n", 1);
	}
}
