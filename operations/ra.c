#include "push_swap.h"

void	ra(int *A, int *size_a, t_ops *ops)
{
	int	a;
	int	i;
	int	tmp;

	i = 0;
	a = *size_a;
	if (a > 1)
	{
		tmp = A[0];
		while (a - 1 > i)
		{
			A[i] = A[i + 1];
			i++;
		}
		A[i] = tmp;
		ops->ra++;
		ops->total++;
		ft_putstr_fd("ra\n", 1);
	}
}
